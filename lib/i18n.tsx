const dicts: Record<Lang, typeof he> = { he, ar, ru };
export type TKey = keyof typeof he;

export const LANG_NAMES: Record<Lang, string> = { he: 'עברית', ar: 'العربية', ru: 'Русский' };

/** Shows a native picker with all 3 languages; calls setLang on selection. */
export function showLanguagePicker(setLang: (l: Lang) => void, cancelLabel: string) {
  Alert.alert('', '', [
    { text: LANG_NAMES.he, onPress: () => setLang('he') },
    { text: LANG_NAMES.ar, onPress: () => setLang('ar') },
    { text: LANG_NAMES.ru, onPress: () => setLang('ru') },
    { text: cancelLabel, style: 'cancel' },
  ]);
}

interface I18nValue {
  lang: Lang;
  t: (key: TKey) => string;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('he');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((v) => {
      if (v === 'he' || v === 'ar' || v === 'ru') setLangState(v);
    });
  }, []);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      t: (key) => dicts[lang][key] ?? key,
      setLang: (l) => {
        setLangState(l);
        AsyncStorage.setItem(STORAGE_KEY, l);
      },
      toggleLang: () => {
        const order: Lang[] = ['he', 'ar', 'ru'];
        const next = order[(order.indexOf(lang) + 1) % order.length];
        setLangState(next);
        AsyncStorage.setItem(STORAGE_KEY, next);
      },
    }),
    [lang]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
